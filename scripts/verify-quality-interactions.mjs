import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { writeFile } from 'node:fs/promises';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_PACKAGE || 'playwright');
const browser = await chromium.launch({headless:true,...(process.env.CHROME_EXECUTABLE?{executablePath:process.env.CHROME_EXECUTABLE}:{})});
const evidence = [];
try {
  const page = await browser.newPage({viewport:{width:320,height:844},reducedMotion:'reduce'});
  await page.route('**/api/bitoguard/**',r => r.fulfill({status:503,contentType:'application/json',body:'{"error":"temporarily unavailable"}'}));
  await page.goto('http://127.0.0.1:8787/bitoguard/');
  await page.getByRole('button',{name:'重新載入資料',exact:true}).waitFor({timeout:20000});
  assert.match(await page.getByRole('alert').filter({hasText:'部分展示資料暫時無法載入'}).innerText(),/部分展示資料暫時無法載入/);
  await page.unroute('**/api/bitoguard/**');
  await page.getByRole('button',{name:'重新載入資料',exact:true}).click();
  await page.getByText('demo-user-001',{exact:true}).waitFor();
  evidence.push('BitoGuard API failure is visible and retry restores dashboard data');
  await page.getByText('AP (Average Precision)',{exact:true}).waitFor({timeout:3000});
  await page.goto('http://127.0.0.1:8787/bitoguard/alerts/report/?alertId=demo-alert-001');
  const riskScore=page.getByText('0.94',{exact:true});await riskScore.waitFor();
  assert.equal(await riskScore.evaluate(el=>getComputedStyle(el).color),'rgb(191, 37, 37)');
  await page.goto('http://127.0.0.1:8787/bitoguard/model-ops/');
  await page.getByText('AP = 0.6500',{exact:true}).waitFor();
  const curve=page.getByRole('img',{name:/Precision–Recall 曲線/});
  const labelSize=await curve.evaluate(svg=>Math.min(...Array.from(svg.querySelectorAll('text'),text=>Number(text.getAttribute('font-size'))))*svg.getBoundingClientRect().width/svg.viewBox.baseVal.width);
  assert.ok(labelSize>=12,'Curve labels retain at least 12 rendered pixels on a 320px screen');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.getByText('查看曲線數值',{exact:true}).click();
  const curveRows=await page.locator('details').filter({hasText:'查看曲線數值'}).locator('tbody tr').evaluateAll(rows=>rows.map(row=>Array.from(row.querySelectorAll('td'),cell=>Number(cell.textContent))));
  const metrics=await (await page.request.get('http://127.0.0.1:8787/api/bitoguard/metrics/model')).json();
  assert.deepEqual(curveRows,metrics.pr_curve.recall.map((recall,index)=>[recall,metrics.pr_curve.precision[index]]));
  evidence.push('Average Precision is labeled as AP; critical risk scores agree with their red risk badge');
  evidence.push('PR curve stays readable at 320px and its accessible table matches all API curve points');
  await page.goto('http://127.0.0.1:8787/bitoguard/users/');
  const users=page.getByLabel('選擇用戶',{exact:true});await users.waitFor();
  await users.focus();assert.notEqual(await users.evaluate(el=>getComputedStyle(el).outlineStyle),'none');
  await users.selectOption({index:1});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.goto('http://127.0.0.1:8787/bitoguard/graph/');
  await page.getByText('文字版關聯資料',{exact:false}).click();
  assert.match(await page.locator('details').filter({hasText:'文字版關聯資料'}).innerText(),/demo-user-001/);
  const relation=page.getByRole('button',{name:'使用裝置',exact:true});await relation.focus();await page.keyboard.press('Space');
  assert.equal(await relation.getAttribute('aria-pressed'),'false');
  evidence.push('Named controls, visible keyboard focus, toggle state and text graph are usable at 320px');
  await page.route('**/api/products',r=>r.fulfill({status:503,contentType:'application/json',body:'{"error":"temporarily unavailable"}'}));
  await page.goto('http://127.0.0.1:8787/hw3/');
  await page.getByRole('button',{name:'重新載入展示'}).waitFor();
  await page.unroute('**/api/products');await page.getByRole('button',{name:'重新載入展示'}).click();
  await page.locator('[data-add="notebook"]').waitFor();
  evidence.push('Store initial load failure has an actionable recovery');
  await page.goto('http://127.0.0.1:4173/coursework/hw2/index.html');
  const fog=page.getByLabel('Foggy Mode:',{exact:true});await fog.focus();await page.keyboard.press('Space');
  assert.equal(await fog.getAttribute('aria-pressed'),'true');await page.keyboard.press('Space');
  await page.locator('#start-btn').click();await page.locator('#maze-canvas').waitFor();
  const before=await page.locator('#maze-canvas').evaluate(canvas=>canvas.toDataURL());
  await page.getByRole('button',{name:'向右',exact:true}).click();await page.getByRole('button',{name:'向下',exact:true}).click();
  await page.waitForTimeout(150);
  assert.notEqual(await page.locator('#maze-canvas').evaluate(canvas=>canvas.toDataURL()),before);
  await page.selectOption('#difficulty-select','38');await page.locator('#start-btn').click();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  assert.equal(await page.locator('.maze-scroll').evaluate(el=>el.scrollWidth>el.clientWidth),true);
  evidence.push('Maze toggles work from keyboard; touch arrows move the player; large maze stays inside its scroll region');
  await page.close();
} finally {await browser.close();}
await writeFile('.artifacts/quality-interactions.json',JSON.stringify({at:new Date().toISOString(),evidence},null,2));
console.log(evidence.join('\n'));
